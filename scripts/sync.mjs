function buildAdapters() {
  const out = {};
  for (const a of spec.adapters) {
    if (a.kind === 'native') continue;
    if (a.kind === 'json-context') {
      const files = ['AGENTS.md', byId.dna.filename];
      out[a.path] =
        JSON.stringify(
          {
            $comment: 'Puntero del Tridente de Memoria: el contexto real vive en AGENTS.md.',
            // Esquema actual de Gemini CLI (ajustes anidados).
            context: { fileName: files },
            // Clave plana heredada, para versiones anteriores. Gemini CLI migra
            // automáticamente la plana a la anidada; mantener ambas evita que la
            // migración reescriba el archivo y dispare una falsa deriva.
            contextFileName: files,
          },
          null,
          2,
        ) + '\n';
      continue;
    }
    if (a.kind === 'mdc') {
      out[a.path] = `---
description: ${spec.protocol.name} — protocolo obligatorio de memoria persistente
alwaysApply: true
---

${POINTER_ES(a.tool, a.path)}`;
      continue;
    }
    if (a.kind === 'import') {
      // La ruta del import debe ser la misma que la del enlace del cuerpo: un
      // archivo que usa dos bases distintas para el mismo destino se contradice.
      const depth = a.path.split('/').length - 1;
      const link = depth ? '../'.repeat(depth) + 'AGENTS.md' : 'AGENTS.md';
      out[a.path] = `${POINTER_ES(a.tool, a.path)}
@${link}
`;
      continue;
    }
    out[a.path] = POINTER_ES(a.tool, a.path);
  }
  return out;
}

