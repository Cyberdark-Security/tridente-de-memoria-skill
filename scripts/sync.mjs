/** Sustituye el contenido entre marcadores. Devuelve el texto nuevo. */
export function injectBlocks(text, blocks) {
  let out = text;
  for (const [id, body] of Object.entries(blocks)) {
    const re = new RegExp(
      `(<!--\\s*tridente:begin:${id}\\s*-->)[\\s\\S]*?(<!--\\s*tridente:end:${id}\\s*-->)`,
      'g',
    );
    // Reemplazo con función para que `$` dentro del cuerpo no se interprete.
    out = out.replace(re, (_m, open, close) => `${open}\n${body}\n${close}`);
  }
  return out;
}

/** IDs de marcador presentes en un texto. */
export function markerIds(text) {
  return [...text.matchAll(/<!--\s*tridente:begin:([\w-]+)\s*-->/g)].map((m) => m[1]);
}

