function emit(relPath, content) {
  const abs = join(ROOT, relPath);
  const next = norm(content);
  const prev = existsSync(abs) ? norm(readFileSync(abs, 'utf8').replace(/^﻿/, '')) : null;
  if (prev === next) return;
  if (CHECK) {
    drift.push({ path: relPath, reason: prev === null ? 'falta' : 'desincronizado' });
    return;
  }
  mkdirSync(dirname(abs), { recursive: true });
  // Windows PowerShell 5.1 lee los .ps1 como ANSI si no llevan BOM UTF-8:
  // sin él, los acentos de las preguntas llegan corrompidos al usuario.
  const onDisk = relPath.endsWith('.ps1') ? '﻿' + next.replace(/\n/g, '\r\n') : next;
  writeFileSync(abs, onDisk, 'utf8');
  written++;
  console.log(`  ${prev === null ? '+' : '~'} ${relPath}`);
}

