#!/usr/bin/env node
/**
 * Tridente de Memoria — Generador de documentación (SSOT → artefactos).
 *
 * Lee `protocol/tridente.spec.json` y regenera TODOS los archivos derivados:
 * AGENTS.md, SKILL.md, plantillas, adaptadores por herramienta y los bloques
 * marcados dentro de los README.
 *
 *   node scripts/sync.mjs           escribe los archivos
 *   node scripts/sync.mjs --check   no escribe; sale 1 si algo está desincronizado
 *
 * Sin dependencias externas: sólo Node >= 18.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC_PATH = join(ROOT, 'protocol', 'tridente.spec.json');
const spec = JSON.parse(readFileSync(SPEC_PATH, 'utf8'));

const CHECK = process.argv.includes('--check');
// Cabecera de archivo generado. Va envuelta en marcadores para que
// init-tridente.* pueda retirarla al copiar el archivo a otro proyecto.
const HDR_OPEN = '<!-- tridente:header-start -->';
const HDR_CLOSE = '<!-- tridente:header-end -->';
const BANNER_ES = `${HDR_OPEN}
<!-- GENERADO POR scripts/sync.mjs — NO EDITAR A MANO.
     Fuente de verdad: protocol/tridente.spec.json
     Regenerar con: node scripts/sync.mjs -->
${HDR_CLOSE}`;
const BANNER_EN = `${HDR_OPEN}
<!-- GENERATED BY scripts/sync.mjs — DO NOT EDIT BY HAND.
     Source of truth: protocol/tridente.spec.json
     Regenerate with: node scripts/sync.mjs -->
${HDR_CLOSE}`;

// ---------------------------------------------------------------- utilidades

const byId = Object.fromEntries(spec.files.map((f) => [f.id, f]));
const readFiles = spec.readOrder.map((id) => byId[id]);
const writeFiles = spec.writeOrder.map((id) => byId[id]);
const names = spec.files.map((f) => f.filename);

/** Normaliza saltos de línea para que la comparación no dependa del SO. */
const norm = (s) => s.replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trimEnd() + '\n';

/** Resuelve {dna}/{plan}/{lessons} a los nombres reales del spec. */
function interp(text) {
  return String(text).replace(/\{(dna|plan|lessons)\}/g, (_m, id) => byId[id].filename);
}

/** Bloque de código markdown para un formato de entrada del spec. */
function entryBlock(entry, lang = 'es') {
  const key = lang === 'en' ? 'keyEn' : 'key';
  const hint = lang === 'en' ? 'hintEn' : 'hint';
  const head = entry.headingTemplate
    .replace('{date}', spec.dateFormat.display)
    .replace('{title}', lang === 'en' ? '[Title]' : '[Título]');
  const lines = entry.fields.map(
    (f) => `- **${f[key]}:** [${interp(f[hint])}]${f.required ? '' : ' *(opcional)*'}`,
  );
  return ['```markdown', head, ...lines, '```'].join('\n');
}

/** Tabla markdown a partir de cabeceras y filas. */
function table(headers, rows, align) {
  const sep = headers.map((_, i) => align?.[i] ?? ':---');
  return [
    `| ${headers.join(' | ')} |`,
    `| ${sep.join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

// ------------------------------------------------------- bloques compartidos

/** Tabla de los 3 archivos maestros (usada en README, AGENTS y SKILL). */
function tridentTable(lang = 'es') {
  const en = lang === 'en';
  return table(
    en ? ['File', 'Role', 'Contents'] : ['Archivo', 'Rol', 'Contenido'],
    spec.files.map((f) => [
      `\`${f.filename}\``,
      `${f.emoji} ${en ? f.roleEn : f.role}`,
      en ? f.purposeEn : f.purpose,
    ]),
  );
}

/** Tabla de compatibilidad por herramienta. */
function adapterTable(lang = 'es') {
  const en = lang === 'en';
  const seen = new Set();
  const rows = [];
  for (const a of spec.adapters) {
    const k = a.tool + a.path;
    if (seen.has(k)) continue;
    seen.add(k);
    const mech =
      a.kind === 'native'
        ? en
          ? 'Native'
          : 'Nativo'
        : en
          ? 'Generated adapter'
          : 'Adaptador generado';
    // Algunas herramientas necesitan un paso extra: decirlo aquí evita anunciar
    // como automático algo que no lo es.
    const caveat = a.manual ? (en ? ` — ${a.manualEn}` : ` — ${a.manual}`) : '';
    rows.push([a.tool, `\`${a.path}\``, mech + caveat]);
  }
  return table(en ? ['Tool', 'File it reads', 'Mechanism'] : ['Herramienta', 'Archivo que lee', 'Mecanismo'], rows);
}

/** Tabla de rutas de instalación del skill. */
function installTable(lang = 'es') {
  const en = lang === 'en';
  return table(
    en ? ['Platform', 'Install path'] : ['Plataforma', 'Ruta de instalación'],
    spec.skillInstallPaths.map((p) => [`**${p.platform}**`, `\`${p.path}\``]),
  );
}

